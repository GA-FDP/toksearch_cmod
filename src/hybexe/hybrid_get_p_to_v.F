       function get_input_p_to_v(name,structure)
c
c It is confusing to see two functions of the same name, "get_input_p_to_v", in
c the same library.  What is occurring is that although the names are the same
c in the source files, this file is compiled with name mangling and the other
c file is not.   Thus this function compiles to "get_input_p_to_v_" and the other
c file compiles to "get_input_p_to_v" (no trailing underscore).
c
c Title:	GET_INPUT_P_to_V
c
c Type:		Fortran Function
c
c Purpose:	Return an XD containing calibration (Physical Units/Volt) 
c		for a HYBRID input.
c
c Description:	The calling environment is determined by a call to GETDBI to 
c		distinguish whether the CMOD experiment tree is the current
c		tree.
c
c		Based on the value of STRUCTURE, a canned routine (see below)
c		is used to return the appropriate calibration value for the
c		diagnostic signal designated by NAME. 
c
c		The additional calibration required to account for
c		circuitry associated with the HYBRID inputs, 
c		e.g. gain of the isolation amplifiers, is applied to the  
c		result.  
c
c               This routine is not called directly, but is invoked by
c               an interface routine of the same name (compile with 
c               -fno-underscoring) located in get_input_p_to_v_int.f 
c               which takes care of passing in the lengths of the null-
c               terminated strings corresponding to the dummy arguments
c               NAME and STRUCTURE. 
c
c		The MDSplus descriptor is generated by a call into 
c               MdsShr->MdsCopyDxXd()
c		and the %loc(data_id) is returned as the function value.
c
c Arguments:	NAME	Character scalar: Must be one of the defined input
c			names for HYBRID input signals, in the sense that the
c			value of NAME together with STRUCTURE uniquely
c			specifies the quantities of interest.
c		STRUCTURE
c			Character scalar: Must be one of the KNOWN_STRUCTURES
c			which specify a function call as described below.
c
c Result:	Address of an MDSPLUS descriptor containing the calibration of 
c		the input specified by the arguments.
c
c Routines:	MdsValue
c               descr
c
c		For each KNOWN_STRUCTURES(i), a function is provided which 
c		returns the calibration as a REAL*4 value.  For structures 
c		involving references external to the HYBRID sub-tree, but 
c		internal to the CMOD tree, a logical argument CMOD_TREE is 
c		provided indicating the present environment.  By convention, 
c		if CMOD_TREE == .TRUE. 	all references are to be resolved 
c		within the currently open tree. If CMOD_TREE==.FALSE. 
c		references are made via the USING function to the MODEL 
c		files of the relevant sub-trees.
c
c               As of 9/15/2011, each KNOWN_STRUCTURES element is associated 
c               with a TARGET_TREE, possibly '', which, if EXPT_TREE.ne.'CMOD' 
c               is opened before calling into the appropriate get_() function.
c               The context is then reset before returning from this routine,
c               but the TARGET_TREE is not explicitly closed. 
c               Doing an explicit MdsOpen() is more efficient than multiple calls
c               to USING(), and leaving the tree available on the stack increases 
c               the efficiency of subsequent calls involving the same TARGET_TREE. 
c
c Remarks:	Default values and results of error returns are set equal to
c		1.0; note that since the usage requires division by a vector
c		combining the results of a sequence of calls, neither zero nor
c		$MISSING is satisfactory as an ERROR RETURN.
c
c		To add new STRUCTURES:
c			1) Increase the value of Num_structures
c			2) Add the new structure to the data statement for
c			   KNOWN_STRUCTURES
c			3) Add a branch on line 999 and a corresponding 
c			   function call 
c			4) Provide a FUNCTION to return the calibration value.
c		
c		No restrictions are imposed on the calling sequence or behavior
c		of the GET_structure routines, but an appropriate call must
c		be inserted into this code for each known structure/function.
c
c Restrictions:	No validation information is returned; Errors result in a
c		return value of 1.0
c
c		No units are returned.
c
c		Gain of isolation amplifiers is "hard-wired" to 2.0 by
c		PARAMETER (GAIN_ISO) (obsolete)
c
c		Error and informational messages are written to SYS$OUTPUT
c
c		The functions must not change the current context. 
c
c Calling Sequence:
c		From TDI:	IMAGE->GET_INPUT_P_to_V:DSC(name,structure)
c
c Revisions:	0.0	6/18/91	smw
c		0.2	1/22/93	smw	Add Structures BUS_ROGOWSKI,PS_CURRENT
c					Fix bug in typing of CMOD_TREE as logical*1
c		0.3	4/18/93 smw	Add Structure MAG_BTOR
c		0.4	4/24/93 smw	Get rid of USING in GET_MAG_FLUX_FULL,
c					GET_MAG_FLUX_PARTIAL, and GET_MAG_BTOR
c		0.5	4/25/93 smw	Take GAIN_ISO division out of HYB_REFERENCE sequence
c		0.6	5/24/93 smw	Take GAIN_ISO out of this code entirely. Tree
c					expression should now explicitly divide by 
c					P_TO_V_EXPR:GAIN
c               1.0     4/9/2002 smw    Modify for Linux, changing filename to .f 
c               1.1     2/21/2003 smw   Add "CONSTANT" to known-structures, 
c                                       return 1.0 (v0.7 of VMS edition)
c               1.2     9/07/2011       Adapt source for multi-platform (i386, x86_64) 
c                                       Using cpp pre-processing directives in .F file
c               1.3     9/15/2011       Add tree open, context saving logic to 
c                                       get_input_p_to_V(), remove from called functions.
********************************************************************************
      include 'mdslib.inc'
c #ifdef __x86_64__
      parameter(NSizeXd=20)
c #endif
c #ifdef __i386__
c       parameter(NSizeXd=12)
c #endif
      byte            Xd(NSizeXd),blankXd(NSizeXd),CLASS_XD
      parameter	(Num_structures=9)
      parameter (CLASS_XD=192)
      character*(*)	name,structure
      logical*1	        NEED_TARG
      integer(kind=8) 	get_input_P_to_V
c     
      character*12	EXPT_NAME, TARGET_TREES(Num_structures)
      character*12      NO_TREE,CMOD_TREE
      character*30	KNOWN_STRUCTURES(Num_structures)
      character*100     default
      integer*4 	LENGTH,source_shot
      integer           context_status,target_status
c     
      data blankXd(4)	/CLASS_XD/
      data KNOWN_STRUCTURES /'MAG_FLUX_FULL','MAG_BP_COILS',
     $     'MAG_ROGOWSKIS',
     $     'MAG_FLUX_PARTIAL','HYB_REFERENCE',
     $     'BUS_ROGOWSKI','PS_CURRENT','MAG_BTOR',
     $     'CONSTANT'/
      data TARGET_TREES /4*'MAGNETICS','',2*'ENGINEERING',
     $      'MAGNETICS','' /
      data CMOD_TREE /'CMOD'/
      data NO_TREE /''/
c     
c     First, check for known structure code; return with error if not found
c     Also, make sure both name and structure have non-zero length
c     
      if (len(name) .eq. 0) then 
         write (6,*) 'Error -- Name has zero length'
         cal = 1.
         go to 500
      endif
      if (len(structure) .eq. 0) then 
         write (6,*) 'Error -- Structure name has zero length'
         cal = 1.
         go to 500
      endif
      do istruc=1,Num_structures
         if (structure .eq. KNOWN_STRUCTURES(istruc)) go to 400
      end do
      write (6,*) 'ERROR -- Unknown structure name ',structure
      cal = 1.
      go to 500
c     
c     If structure is known, determine the calling context
c     
 400  continue
      if (.not. btest(MdsValue('getdbi("NAME",0)'//char(0),
     .       descr(IDTYPE_CSTRING,EXPT_NAME,0,12),0,LENGTH),0)) then 
         cal = 1.
         write (6,*) 'Error -- Tree not open.'
         go to 500
      endif
      NEED_TARG=((TARGET_TREES(istruc).ne.NO_TREE)
     .     .and.(EXPT_NAME.ne.CMOD_TREE))
      if (NEED_TARG) then
         context_status = 0
         if (btest(MdsValue('getdbi("DEFAULT")'//char(0),
     .        descr(IDTYPE_CSTRING,default,0,100),0,length),0)) then
            if (btest(MdsValue('getdbi("SHOT")'//char(0),
     $           descr(IDTYPE_LONG,source_shot,0),0,length),0))then
               context_status = 1
            else 
               write(6,*) ' Error getting current shot'
            endif
         else
            write(6,*) ' Error getting current DEFAULT'
         endif
         if (btest(context_status,0)) then 
            call open_target_tree(TARGET_TREES(istruc),source_shot,
     .           target_status)
            if (.not.btest(target_status,0)) then 
               cal = 1.
               write(6,*) 'Invalid tree ',TARGET_TREES(istruc),
     .              ' for STRUCTURE ',structure
               goto 500
            endif
         endif
      endif
 999  go to (10,20,30,40,50,60,70,80,90) istruc
c MAG_FLUX_FULL
 10   cal = get_mag_flux_full(name)
      go to 500
c MAG_BP_COILS
 20   cal = get_mag_bp_coils(name)
      go to 500
c MAG_ROGOWSKIS
 30   cal = get_mag_rogowskis(name)
      go to 500
c MAG_FLUX_PARTIAL
 40   cal = get_mag_flux_partial(name)
      go to 500
c HYB_REFERNCE
 50   cal = get_HYB_REFERENCE(name)
      go to 500
c BUS_ROGOWSKI
 60   cal = get_bus_rogowskis(name)
      go to 500
c PS_CURRENT
 70   cal = get_PS_CURRENTs(name)
      go to 500
c MAG_BTOR
 80   cal = get_MAG_BTOR(name)
      go to 500
c CONSTANT
 90   cal=1.0
      go to 500
 500  continue
c Restore original context, if possibly changed
      if (NEED_TARG) then
         call restore_context(EXPT_NAME,source_shot,default,
     .        context_status)
         if (.not.btest(context_status,0)) then 
            write(6,*) 'Error resetting tree context!'
         endif
      endif
c Stuff CAL into an extended MDSplus descriptor
c	call mds$get('$',%descr(cal),id)
      istat=MdsValue('_xd=$,'//
     .     'MdsShr->MdsCopyDxXd(descr($),ref(_xd)),_xd'//char(0),
     .     descr(IDTYPE_BYTE,blankXd,NSizeXd,0),
     .     descr(IDTYPE_FLOAT,cal,0),
     .     descr(IDTYPE_BYTE,xd,NSizeXd,0),0,mdslen)
      get_input_P_to_V = %loc(xd)
      return
      end
************************************************************************
      subroutine restore_context(tree,shot,default,status)
c Title:       RESTORE_CONTEXT
c
c Type:		Fortran Subroutine
c
c Purpose:      Reopens original tree and sets default 
c
c Arguments: 
c          TREE   Character*  Intent In   Name of currently open tree
c          SHOT   Integer     Intent In   Shot number of current tree
c          DEFAULT Charcter   Intent In   Default location 
c          STATUS INTEGER     Intent OUT   Odd for success, Even for failure
c Revisions:
c          Introduced 14-Sep-2011 /smw
************************************************************************
        include 'mdslib.inc'
        character     tree*12,default*100 
        integer       shot
        integer       status
c
        status = MdsOpen(tree//char(0),shot)
        status = MdsSetDefault(default//char(0))
        return
        end
************************************************************************
      subroutine open_target_tree(tree,shot,status)
c Title:       OPEN_TARGET_TREE
c
c Type:		Fortran Subroutine
c
c Purpose:      Opens a new tree for use by one of the Hybexe GET_* 
c               functions. If opening the target shot number fails,
c               then the model (-1) file is opened.   
c
c Arguments: 
c          TREE   Character*12  Intent In   Name of currently open tree
c          SHOT   Integer     Intent In   Shot number of current tree
c          STATUS INTEGER     Intent OUT   Odd for success, Even for failure
c Revisions:
c          Introduced 14-Sep-2011 /smw
************************************************************************
        include 'mdslib.inc'
        character*12  tree 
        integer       shot
        integer       status
c
        status = MdsOpen(tree(1:len_trim(tree))//char(0),shot)
        if ((.not.btest(status,0)).and.(shot.ne.-1)) then 
           status = MdsOpen(tree//char(0),-1) 
        endif
        if (.not.btest(status,0)) then
           write(6,*) 'Error opening TREE ',tree,'shot ',shot
        endif
        return
        end
