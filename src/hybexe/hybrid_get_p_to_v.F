	function get_bus_rogowskis(name)
c
c Title:	get_bus_rogowskis
c
c Type:		Fortran Function
c
c Purpose:	Returns the calibration of a HYBRID input named "name" 
c		having structure BUS_ROGOWSKI
c
c Description:	All information is retrieved from the ENGINEERING Sub-tree.
c		The calling environment indicated by CMOD_TREE determines
c		whether references are to the CMOD tree or the model file.
c
c		\ENGINEERING.POWER_SYSTEM.* is searched for a match to the input
c		string NAME.
c
c		The :INTEGR_TAU time constant of the node specified by NAME,
c		divided by the corresponding :CALIBRATION is returned as the 
c		calibration.
c
c		Error conditions result in a message to SYS$OUTPUT and a return
c		value of 1.0
c
c Arguments:	NAME	Character scalar: Must be one of the defined input
c			names for HYBRID input signals, in the sense that the
c			value of NAME together with STRUCTURE uniquely
c			specifies the quantities of interest.
c Result:	Address of a REAL*4 scalar containing the calibration value.
c
c Routines:	MDSVALUE
c               descr
c
c Remarks:	Default values and results of error returns are set equal to
c		1.0; note that since the usage requires division by a vector
c		combining the results of a sequence of calls, neither zero nor
c		$MISSING is satisfactory as an ERROR RETURN.
c
c Restrictions:	No validation information is returned; Errors result in a
c		return value of 1.0
c
c		No units are returned.
c
c		Error and informational messages are written to SYS$OUTPUT
c
c Revisions:	0.2	1/22/93	smw
c               0.3     9/14/2011 smw Get rid of USING() calls, do 
c                                     save_context, open_target_tree, restore_context
********************************************************************************
        include 'mdslib.inc'
	real*4		get_bus_rogowskis
	character*(*)	name
c
	character*60	cpath,tpath
	real*4		INTEGR_TAU,CALIBRATION
	integer*4	LENGTH,cstatus,tstatus
c
	cpath = '\ENGINEERING::'//name//':CALIBRATION'
	tpath = '\ENGINEERING::'//name//':INTEGR_TAU'
        cstatus = MdsValue(cpath//char(0),
     $       descr(IDTYPE_FLOAT,CALIBRATION,0), 0,LENGTH)
        tstatus = MdsValue(tpath//char(0),
     $       descr(IDTYPE_FLOAT,INTEGR_TAU,0), 0,LENGTH)
	if ((btest(cstatus,0)) .and. (btest(tstatus,0))) then 
           if (CALIBRATION .ne. 0.) then
              get_bus_rogowskis = INTEGR_TAU / CALIBRATION
           else
              get_bus_rogowskis = 1.
              write (6,9002) name
           endif
	else 
           get_bus_rogowskis = 1.
           write (6,9001) name,cstatus,tstatus
	endif
	return
 9001	format(	' Error reading calibration data for input ',a/
     $       ' CSTATUS = ',i10/
     $       ' TSTATUS = ',i10/
     $       ' PHYS_TO_VOLTS set to 1.0')
 9002	format( ' Error in calibration data for input ',a/
     $       ' CALIBRATION value is equal to zero.'/
     $       ' PHYS_TO_VOLTS set to 1.0')
	end
