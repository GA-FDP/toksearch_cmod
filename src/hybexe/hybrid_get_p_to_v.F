	function GET_HYB_REFERENCE(name)
c
c Title:	GET_HYB_REFERENCE
c
c Type:		Fortran Function
c
c Purpose:	Returns the calibration of a HYBRID input named "name" 
c		having structure HYB_REFERENCE. This structure is intended 
c		for special reference inputs for the WAVEGEN.
c
c Description:	All information is hardwired in the routine.
c
c		The only valid value for NAME is "REF_ONE". A 
c		calibration value of 1.0 corresponding to a logical 
c		ONE is returned for this case.  

c		Error conditions result in a message to SYS$OUTPUT and a return
c		value of 1.0
c
c Arguments:	NAME	Character scalar: Must be one of the defined input
c			names for HYBRID input signals. Presently restricted to
c			"REF_ONE".
c
c Result:	Address of a REAL*4 scalar containing the calibration value.
c
c Routines:	none
c
c Remarks:	Default values and results of error returns are set equal to
c		1.0; note that since the usage requires division by a vector
c		combining the results of a sequence of calls, neither zero nor
c		$MISSING is satisfactory as an ERROR RETURN.
c
c Restrictions:	No validation information is returned; Errors result in a
c		return value of 1.0
c
c		No units are returned.
c
c		Error and informational messages are written to SYS$OUTPUT
c
c		Only the value REF_ONE is recognized as a valid input argument.
c
c Revisions:	0.0	6/18/91	smw
c		0.1	4/25/93 smw Changed return for REF_ONE to 1.0
********************************************************************************
	character*(*)	name
c
	if (name .eq. 'REF_ONE') then 
		GET_HYB_REFERENCE = 1.0
	else
		GET_HYB_REFERENCE = 1.
		write (6,*) 'Error -- Unknown NAME in HYB_REFERENCE.'
	endif
	return
	end
