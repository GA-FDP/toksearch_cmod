	function get_mag_flux_full(name)
c
c Title:	GET_MAG_FLUX_FULL
c
c Type:		Fortran Function
c
c Purpose:	Returns the calibration of a HYBRID input named "name" 
c		having structure MAG_FLUX_FULL
c
c Description:	All information is retrieved from the MAGNETICS Sub-tree.
c		The calling environment indicated by CMOD_TREE determines
c		whether references are to the CMOD tree or the model file.
c
c		\MAG_FLUX_FULL:nodename is searched for a math to the input
c		string NAME.
c
c		The RC time constant of the corresponding element of CIRCUITS
c		is returned as the calibration.
c
c		Error conditions result in a message to SYS$OUTPUT and a return
c		value of 1.0
c
c Arguments:	NAME	Character scalar: Must be one of the defined input
c			names for HYBRID input signals, in the sense that the
c			value of NAME together with STRUCTURE uniquely
c			specifies the quantities of interest.
c		CMOD_TREE
c			Logical scalar: .TRUE. if the CMOD tree is the current
c			default tree. Otherwise, .FALSE.
c
c Result:	Address of a REAL*4 scalar containing the calibration value.
c
c Routines:	MDSVALUE
c               descr
c		MDSOPEN
c		MDSSETDEFAULT
c
c Remarks:	Default values and results of error returns are set equal to
c		1.0; note that since the usage requires division by a vector
c		combining the results of a sequence of calls, neither zero nor
c		$MISSING is satisfactory as an ERROR RETURN.
c
c Restrictions:	No validation information is returned; Errors result in a
c		return value of 1.0
c
c		No units are returned.
c
c		Error and informational messages are written to SYS$OUTPUT
c
c Revisions:	0.0	6/18/91	smw
c		0.1	4/1/92	smw	Look for - signs in decompile of nodes
c		0.2	4/24/93 smw	Get rid of the USINGs; open and close MAGNETICS
c               1.1     9/11/2009 smw   Increase dim of decompile from 100 to 255
c               1.2     9/15/2011       Remove CMOD_TREE logic, now in caller
********************************************************************************
c
        include 'mdslib.inc'
	real*4		get_mag_flux_full
	character*(*)	name
c     
	character*12	nodenames(0:199)
        character*255   decompile
	character*40	path
	real*4		RC	
	integer*4	LENGTH
	integer*4	CIRCUIT
C     
c     
c     
	path = '\magnetics::mag_flux_full.signals:'//name
	get_mag_flux_full = 1.0
	if (btest(MdsValue('\magnetics::mag_flux_full:nodename'//char(0),
     $       descr(IDTYPE_CSTRING,nodenames,200,0,12),0,LENGTH),0)) then 
           do i=0,length-1
              if (nodenames(i) .eq. name) go to 10
           end do
           write (6,*) 'Error -- Unknown node name'
           go to 100
	else 
           write (6,*) ' Error getting NODENAMES'
           go to 100
	endif
 10	istat=MdsValue('\magnetics::mag_flux_full:circuits[$]'//char(0),
     $       descr(IDTYPE_LONG,i,0),descr(IDTYPE_LONG,CIRCUIT,0),0,
     $       LENGTH)
	istat=MdsValue('\magnetics::mag_circuits:rc_values[$]'//char(0),
     $       descr(IDTYPE_LONG,CIRCUIT,0),descr(IDTYPE_FLOAT,RC,0),0,
     $       LENGTH)
	istat=MdsValue('decompile(`getnci($,"record"))'//char(0),
     $       descr(IDTYPE_CSTRING,path,0,40),
     $       descr(IDTYPE_CSTRING,decompile,0,255),0,length)
	get_mag_flux_full = RC
	ipos = index(decompile,'* -') 
	if (ipos .gt. 0) get_mag_flux_full = -get_mag_flux_full
 100	continue
	return
	end
