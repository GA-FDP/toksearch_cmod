      function get_MAG_BTOR(name)
c
c Title:	GET_MAG_BTOR
c
c Type:		Fortran Function
c
c Purpose:	Returns the calibration of a HYBRID input named "name" 
c		having structure MAG_BTOR
c
c Description:	All information is retrieved from the MAGNETICS Sub-tree.
c		The calling environment indicated by CMOD_TREE determines
c		whether references are to the CMOD tree or the model file.
c
c		This structure refers to a single signal node in the magnetics
c		tree, which actually corresponds to the diamagnetic compensation
c		loop. 
c		The node \MAG_BTOR is decompiled. The resulting string is then parsed 
c		for an expresion corresponding to the calibration. This 
c		string expression is passed to MDSVALUE to be evaluated and 
c		the result is returned. 
c
c		Error conditions result in a message to SYS$OUTPUT and a return
c		value of 1.0
c
c Arguments:	NAME	Character scalar: Must be one of the defined input
c			names for HYBRID input signals, in the sense that the
c			value of NAME together with STRUCTURE uniquely
c			specifies the quantities of interest.  In this case, 
c			NAME == "BTOR" is the only valid value.
c Result:	Address of a REAL*4 scalar containing the calibration value.
c
c Routines:	MDSVALUE
c               descr
c
c Remarks:	Default values and results of error returns are set equal to
c		1.0; note that since the usage requires division by a vector
c		combining the results of a sequence of calls, neither zero nor
c		$MISSING is satisfactory as an ERROR RETURN.
c
c Restrictions:	No validation information is returned; Errors result in a
c		return value of 1.0
c
c		No units are returned.
c
c		Error and informational messages are written to SYS$OUTPUT
c
c Revisions:	0.1	4/18/93 smw
c		0.2	4/24/93 smw	Get rid of USINGs in favor of 
c					MDSOPEN("MAGNETICS",-1),
c					...
c					MDSOPEN(here_tree,here_shot)
c               0.3     9/11/2009 smw   Increase dim of decompile,cal_expression 
c                                       from 100 to 255
c               0.4     9/15/2011       Remove CMOD_TREE logic, now in caller
********************************************************************************
c
      include 'mdslib.inc'
      real*4		get_mag_btor
      character*(*)	name
c     
      character*255	decompile,cal_expression
      character*40	path
      integer*4	LENGTH,status
      integer*4	ipos,iend
c     
c     
      path = '\magnetics::mag_btor'
      status = MdsValue('decompile(`getnci($,"record"))'//char(0),
     $     descr(IDTYPE_CSTRING,path,0,40),
     $     descr(IDTYPE_CSTRING,decompile,0,255),0,length)
      if ((.not. btest(status,0)) .or. (length.eq.0)) then 
         write(6,*) ' %GET_MAG_BTOR -- Error reading \MAG_BTOR .'
         write(6,*) status,length
         get_MAG_BTOR = 1.
         go to 100
      endif
c     
c     The format of the decompile expression should be
c     'Build_with_Units(\MAGNETICS::camac_hardware_node * 1. /.367 * (.66 / .761) ,"tesla")'
c     from which we need to pull out the numbers
c     
      ipos = index(decompile,'*')+1
      iend = index(decompile,',')-1
      if (iend .le. 0) iend=len_trim(decompile)
c      status = str$pos_extr(cal_expression,decompile,ipos,iend)
      cal_expression=decompile(ipos:iend)
c     
c     Now use MDS to evaluate this expression
c     
      status = MdsValue(cal_expression//char(0),
     $     descr(IDTYPE_FLOAT,get_MAG_BTOR,0),0,length)
      if ((.not.btest(status,0)).or.(length.eq.0)) then
         write(6,*) ' %GET_MAG_BTOR -- '//
     $        'Error evaluating calibration expression'
         write(6,*) status,length,cal_expression
         get_MAG_BTOR = 1.
      endif
c     
 100  continue
      return
      end
